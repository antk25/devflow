"""Model/effort policy: session × phase × complexity → {harness, model, effort}, read from a user-editable JSON."""
import json
import os
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

from .documents import WorkflowError
from .storage import atomic_write

REQUIRED = ('claude', 'pi', 'limits')
PHASES = ('research', 'plan', 'implement')
SOURCE_DIR = Path(__file__).resolve().parents[2] / 'agents'
MARKER = '<!-- generated by devflow install.sh from model-policy.json; edit agents/{phase}.md -->'
MARKER_KEY = 'generated by devflow install.sh from model-policy.json'
ALIASES = {'claude-opus-': 'opus', 'claude-fable-': 'fable', 'claude-sonnet-': 'sonnet', 'claude-haiku-': 'haiku'}


def claude_dir():
    return Path(os.environ.get('DEVFLOW_CLAUDE_DIR', str(Path.home() / '.claude')))


def policy_path():
    return Path(os.environ.get('DEVFLOW_MODEL_POLICY', str(claude_dir() / 'devflow/model-policy.json')))


def load(path):
    if not path.exists():
        return None
    try:
        policy = json.loads(path.read_text())
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        raise WorkflowError(f'Model policy is not valid JSON: {path}: {e}')
    missing = [k for k in REQUIRED if not isinstance(policy, dict) or k not in policy]
    if missing:
        raise WorkflowError(f'Model policy {path} lacks keys: ' + ', '.join(missing))
    required = [('claude', phase) for phase in PHASES] + [('pi', 'implement')]
    if isinstance(policy['pi'], dict):
        required += [('pi', phase) for phase in PHASES if phase != 'implement' and phase in policy['pi']]
    incomplete = [f'{host}/{phase}' for host, phase in required
                  if not isinstance(policy[host], dict) or 'default' not in policy[host].get(phase, {})]
    if incomplete:
        raise WorkflowError(f'Model policy {path} has no default column for: ' + ', '.join(incomplete))
    for host in ('claude', 'pi'):
        for phase, columns in policy[host].items():
            if phase == 'roles' or not isinstance(columns, dict):
                continue
            for column, entry in columns.items():
                harness = entry.get('harness', host) if isinstance(entry, dict) else None
                if not isinstance(harness, str) or not harness:
                    raise WorkflowError(f'Model policy {path} {host}/{phase}/{column}: harness must be a non-empty string')
                if host == 'pi' and harness == 'claude':
                    raise WorkflowError(f'Model policy {path} {host}/{phase}/{column}: a pi session cannot run harness claude')
    return policy


def resolve(policy, host, phase, complexity=None, exhausted=False):
    phases = policy.get(host)
    if not isinstance(phases, dict) or phase not in phases:
        raise WorkflowError(f'Model policy has no entry for {host}/{phase}')
    columns = phases[phase]
    if 'default' not in columns:
        raise WorkflowError(f'Model policy {host}/{phase} has no default column')
    if exhausted and 'fallback' in columns:
        column = 'fallback'
    elif complexity == 'high' and 'high' in columns:
        column = 'high'
    else:
        column = 'default'
    entry = columns[column]
    return {'model': entry['model'], 'effort': entry['effort'], 'column': column, 'harness': entry.get('harness', host)}


def alias(model_id):
    for prefix, name in ALIASES.items():
        if model_id.startswith(prefix):
            return name
    return None


def pi_model(entry):
    return entry['model'] + (':' + entry['effort'] if entry.get('effort') else '')


def resolve_pi_role(policy, role, env, override=None):
    entry = (policy or {}).get('pi', {}).get('roles', {}).get(role)
    if override:
        return {'model': override, 'model_source': 'override'}
    if entry is not None:
        if not isinstance(entry, dict) or not isinstance(entry.get('model'), str) or not entry['model']:
            raise WorkflowError(f'Invalid pi.roles.{role}: expected model and optional effort')
        return {'model': pi_model(entry), 'model_source': f'pi.roles.{role}'}
    provider, model = env.get('PI_PROVIDER'), env.get('PI_MODEL')
    chosen = f'{provider}/{model}' if provider and model else None
    if chosen and env.get('PI_REASONING_LEVEL'):
        chosen += ':' + env['PI_REASONING_LEVEL']
    return {'model': chosen, 'model_source': 'inherited' if chosen else 'default'}


def limits_path():
    return Path(os.environ.get('DEVFLOW_RATE_LIMITS', str(claude_dir() / 'devflow/rate-limits.json')))


def limits(path, threshold, max_age_min, now):
    """rate-limits.json → {exhausted, window, used_percentage, resets_at, at}; None if absent, stale or broken."""
    path = Path(path)
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text())
    except (json.JSONDecodeError, UnicodeDecodeError):
        return None
    at = data.get('at') if isinstance(data, dict) else None
    if not isinstance(at, (int, float)) or now - at > max_age_min * 60:
        return None
    windows = [(name, w['used_percentage'], w.get('resets_at')) for name in ('five_hour', 'seven_day')
               if isinstance(w := data.get(name), dict) and isinstance(w.get('used_percentage'), (int, float))]
    if not windows:
        return {'exhausted': False, 'window': None, 'used_percentage': None, 'resets_at': None, 'at': at}

    def blown(pct, resets_at):
        return pct >= threshold and isinstance(resets_at, (int, float)) and now < resets_at

    name, pct, resets_at = max(windows, key=lambda w: (blown(w[1], w[2]), w[1]))
    return {'exhausted': blown(pct, resets_at), 'window': name, 'used_percentage': pct, 'resets_at': resets_at, 'at': at}


BB_PLUGIN = 'provider-claude-code'
BB_WINDOWS = {'five-hour': 'five_hour', 'weekly': 'seven_day'}


def bb_rpc(binary, method, payload, timeout):
    out = subprocess.run([binary, 'plugin', 'rpc', 'call', BB_PLUGIN, f'provider-usage.v1.{method}',
                          '--input-file', '/dev/stdin', '--json'],
                         input=json.dumps(payload), capture_output=True, text=True, timeout=timeout, check=True)
    return json.loads(out.stdout)


def bb_limits(now, timeout=5):
    """Window percentages from bb's `provider-usage` RPC in rate-limits.json shape; None outside a bb thread or on any failure."""
    if not os.environ.get('BB_THREAD_ID'):
        return None
    binary = shutil.which('bb')
    if not binary:
        return None
    try:
        resources = bb_rpc(binary, 'listResources', {}, timeout)['resources']
        rid = next(r['id'] for r in resources if r.get('providerId') == 'claude-code')
        usage = bb_rpc(binary, 'getResource', {'resourceId': rid, 'refresh': False}, timeout)['usage']
        data = {}
        for w in usage['windows'] if usage.get('status') == 'ok' else []:
            name = BB_WINDOWS.get(w.get('kind'))
            if name and w.get('model') is None and name not in data and isinstance(w.get('usedPercent'), (int, float)):
                reset = datetime.fromisoformat(w['resetsAt'].replace('Z', '+00:00')).timestamp() if w.get('resetsAt') else None
                data[name] = {'used_percentage': w['usedPercent'], 'resets_at': int(reset) if reset else None}
    except (OSError, subprocess.SubprocessError, ValueError, KeyError, TypeError, AttributeError, StopIteration):
        return None
    if not data:
        return None
    return {**data, 'model': None, 'at': now, 'source': 'bb'}


def agents_dir():
    return claude_dir() / 'agents'


def agent_names(policy):
    """Only columns run by harness claude get an agent: `<phase>` for default, plus `<phase>-high` when that column differs and `<phase>-fallback` when its effort differs.

    A fallback that changes only the model needs no agent: the driver passes the model alias at spawn time.
    """
    names = []
    for phase in PHASES:
        columns = {c: e for c, e in policy['claude'][phase].items() if e.get('harness', 'claude') == 'claude'}
        default = columns.get('default')
        if default:
            names.append(phase)
        if 'high' in columns and columns['high'] != default:
            names.append(phase + '-high')
        if 'fallback' in columns and (not default or columns['fallback']['effort'] != default['effort']):
            names.append(phase + '-fallback')
    return names


def render_agent(policy, name, source_dir=SOURCE_DIR):
    phase, _, suffix = name.partition('-')
    entry = policy['claude'][phase][suffix or 'default']
    text = (source_dir / f'{phase}.md').read_text()
    m = re.match(r'---\n(.*?)\n---\n', text, re.S)
    if not m:
        raise WorkflowError(f'Agent source has no frontmatter: {source_dir / phase}.md')
    fields = {'name': name, 'model': entry['model'], 'effort': entry['effort']}
    lines = [f'{k}: {fields.pop(k)}' if (k := line.split(':', 1)[0]) in fields else line
             for line in m.group(1).split('\n')]
    lines += [f'{k}: {v}' for k, v in fields.items()]
    return '---\n' + '\n'.join(lines) + '\n---\n' + MARKER.format(phase=phase) + '\n' + text[m.end():]


def installed_stale(policy, directory=None, source_dir=SOURCE_DIR):
    directory = agents_dir() if directory is None else Path(directory)
    stale = []
    for name in agent_names(policy):
        dst = directory / f'{name}.md'
        if not dst.is_file() or dst.read_text() != render_agent(policy, name, source_dir):
            stale.append(name)
    return stale


def is_generated(path):
    path = Path(path)
    return path.is_file() and not path.is_symlink() and MARKER_KEY in path.read_text()


def conflicts(policy, directory, source_dir=SOURCE_DIR):
    """Names from `agent_names` whose file in `directory` is neither ours (marked) nor an old symlink to `agents/<phase>.md`."""
    directory = Path(directory)
    found = []
    for name in agent_names(policy):
        dst = directory / f'{name}.md'
        if not dst.exists() and not dst.is_symlink():
            continue
        ours = dst.is_symlink() and os.readlink(dst) == str(source_dir / f"{name.partition('-')[0]}.md")
        if not ours and not is_generated(dst):
            found.append(name)
    return found


def orphans(policy, directory):
    """Marked files in `directory` for a known phase whose name the policy no longer produces; foreign files are never listed."""
    names = set(agent_names(policy))
    return sorted(p.stem for p in Path(directory).glob('*.md')
                  if p.stem.partition('-')[0] in PHASES and p.stem not in names and is_generated(p))


def write_agents(policy, directory, source_dir=SOURCE_DIR):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    for name in agent_names(policy):
        dst = directory / f'{name}.md'
        content = render_agent(policy, name, source_dir)
        if dst.is_file() and not dst.is_symlink() and dst.read_text() == content:
            yield name, 'ok'
            continue
        atomic_write(dst, content)
        yield name, 'generate'
    for name in orphans(policy, directory):
        (directory / f'{name}.md').unlink()
        yield name, 'remove'


def launch(phase, complexity=None, now=None):
    """`policy`, `limits` + `launch` fields for `route`; only `policy: None` when no policy file is installed."""
    path = policy_path()
    policy = load(path)
    if policy is None:
        return {'policy': None}
    cfg = policy['limits']
    now = time.time() if now is None else now
    args = (cfg.get('threshold', 95), cfg.get('max_age_min', 10), now)
    signal = limits(limits_path(), *args)
    if signal is None and (fresh := bb_limits(now)):
        try:
            atomic_write(limits_path(), json.dumps(fresh) + '\n')
            signal = limits(limits_path(), *args)
        except OSError:
            pass
    exhausted = bool(signal and signal['exhausted'])
    claude = resolve(policy, 'claude', phase, complexity, exhausted)
    pi = resolve(policy, 'pi', phase, complexity, exhausted) if phase in policy['pi'] else None
    agent = f"{phase}-{claude['column']}" if f"{phase}-{claude['column']}" in agent_names(policy) else phase
    model = (alias(claude['model']) or claude['model']) if claude['column'] == 'fallback' else None
    return {'policy': str(path),
            'limits': signal,
            'policy_stale': installed_stale(policy),
            'launch': {'harness': claude['harness'],
                       'claude': {'id': claude['model'], 'effort': claude['effort'], 'model': model, 'agent': agent},
                       'pi': {'model': pi_model(pi), 'harness': pi['harness']} if pi else None}}


def main(argv):
    policy = load(policy_path())
    if policy is None:
        sys.exit(f'MISS model policy {policy_path()}')
    command, args = argv[0], argv[1:]
    if command == 'names':
        print('\n'.join(agent_names(policy)))
    elif command == 'write':
        for name, action in write_agents(policy, args[0]):
            print(f'{action} {Path(args[0]) / name}.md')
    elif command == 'stale':
        for name in installed_stale(policy, args[0]):
            print(f'STALE agent {name}')
        for name in orphans(policy, args[0]):
            print(f'ORPHAN agent {name}')
    elif command == 'conflicts':
        for name in conflicts(policy, args[0]):
            print(f'{Path(args[0]) / name}.md')
    else:
        sys.exit(f'Unknown policy command: {command}')


if __name__ == '__main__':
    main(sys.argv[1:])
